return function(im,value,x,y,ink)
  for _,code in utf8.codes(value) do
    local ch=utf8.char(code)
    local glyph=assert(glyphs[ch],'Missing preview glyph: '..ch)
    for row,bits in ipairs(glyph) do for col=1,#bits do
      if bits:sub(col,col)=='1' then
        assert(x+col-1<im.width and y+row-1<im.height,'Preview text overflow')
